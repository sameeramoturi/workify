export function searchLocations(query) {
  if (!query) return RAJAHMUNDRY_LOCALITIES;
  const q = query.toLowerCase().trim();
  const matchedLocalities = RAJAHMUNDRY_LOCALITIES.filter(
    l => l.name.toLowerCase().includes(q) || l.pincode.includes(q) || l.landmarks.toLowerCase().includes(q)
  );
  const matchedCities = ANDHRA_PRADESH_CITIES.filter(
    c => c.name.toLowerCase().includes(q) || c.district.toLowerCase().includes(q)
  );
  return { localities: matchedLocalities, cities: matchedCities };
}
